// 库版本
// ---------------------------------------------------------------------------
#define AIKIT_VERSION "0.1.0"
#define AIKIT_VERSION_MAJOR 0
#define AIKIT_VERSION_MINOR 1
#define AIKIT_VERSION_PATCH 0
